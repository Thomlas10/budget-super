// ===== UNIVERSAL TEXT SWITCHER =====
function translateEntireDOM() {
    const lang = localStorage.getItem('app_language') || 'fr';
    const dict = appTranslations[lang];
    if (!dict) return;

    // Translate all elements with text content
    const elements = document.querySelectorAll(
        'h1, h2, h3, h4, h5, h6, p, span, label, button, option, a, td, th, div'
    );

    elements.forEach(el => {
        // Only translate elements with direct text content (no nested elements)
        if (el.children.length === 0) {
            const text = el.textContent.trim();
            if (dict[text]) {
                el.textContent = dict[text];
            }
        } else {
            // For elements with children, only translate direct text nodes
            el.childNodes.forEach(node => {
                if (node.nodeType === Node.TEXT_NODE) {
                    const text = node.textContent.trim();
                    if (text && dict[text]) {
                        node.textContent = node.textContent.replace(text, dict[text]);
                    }
                }
            });
        }
    });

    // Translate placeholders
    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
        const placeholder = el.placeholder.trim();
        if (dict[placeholder]) {
            el.placeholder = dict[placeholder];
        }
    });
}
