function updatePageLanguage() {
    const lang = localStorage.getItem('app_language') || 'fr';
    const t = translations[lang] || translations['fr'];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t[key]) {
            el.textContent = t[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key]) {
            el.placeholder = t[key];
        }
    });
}

class TranslationManager {
    constructor() {
        this.language = this.loadLanguage();
    }

    loadLanguage() {
        const saved = localStorage.getItem('app_language');
        return saved && ['fr', 'en', 'es'].includes(saved) ? saved : 'fr';
    }

    setLanguage(lang) {
        if (['fr', 'en', 'es'].includes(lang)) {
            this.language = lang;
            localStorage.setItem('app_language', lang);
        }
    }

    get(key) {
        return translations[this.language]?.[key] || translations['fr']?.[key] || key;
    }
}

const translationManager = new TranslationManager();

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        const text = translationManager.get(key);
        if (element.tagName === 'OPTION') {
            element.textContent = text;
        } else if (element.tagName === 'LABEL' || element.tagName === 'H2' || element.tagName === 'H3' || element.tagName === 'BUTTON' || element.className.includes('description')) {
            element.textContent = text;
        } else {
            element.textContent = text;
        }
    });
}

class CurrencyManager {
    constructor() {
        this.currency = this.loadCurrency();
        this.listeners = [];
        this.EUR_TO_USD = 1.10;
    }

    loadCurrency() {
        const saved = localStorage.getItem('app_currency');
        return saved === 'USD' ? 'USD' : 'EUR';
    }

    getCurrency() {
        return this.currency;
    }

    getSymbol() {
        return this.currency === 'USD' ? '$' : '€';
    }

    format(amount) {
        if (this.currency === 'USD') {
            const convertedAmount = amount * this.EUR_TO_USD;
            return convertedAmount.toFixed(2).replace('.', '.') + '$';
        } else {
            return amount.toFixed(2).replace('.', ',') + '€';
        }
    }

    setCurrency(code) {
        if (code !== 'EUR' && code !== 'USD') return;
        this.currency = code;
        localStorage.setItem('app_currency', code);
        this.notifyListeners();
    }

    onCurrencyChange(callback) {
        this.listeners.push(callback);
    }

    notifyListeners() {
        this.listeners.forEach(callback => callback(this.currency));
    }
}

