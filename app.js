class Router {
    constructor() {
        const savedPage = localStorage.getItem('current_page');
        this.currentPage = savedPage || 'dashboard';
        this.setupEventListeners();
        this.navigateTo(this.currentPage);
    }

    setupEventListeners() {
        // Listen for nav button clicks
        document.querySelectorAll('.nav-link').forEach(link => {
            link.addEventListener('click', (e) => {
                e.preventDefault();
                const page = link.getAttribute('data-page');
                this.navigateTo(page);
            });
        });
    }

    navigateTo(page) {
        // Hide all pages
        document.querySelectorAll('.page').forEach(section => {
            section.classList.remove('active');
        });

        // Remove active state from all nav links
        document.querySelectorAll('.nav-link').forEach(link => {
            link.classList.remove('active');
        });

        // Show target page
        const targetSection = document.getElementById(page);
        if (targetSection) {
            targetSection.classList.add('active');
        }

        // Mark nav link as active
        const activeLink = document.querySelector(`[data-page="${page}"]`);
        if (activeLink) {
            activeLink.classList.add('active');
        }

        this.currentPage = page;
        localStorage.setItem('current_page', page);

        // Force the Rapport to reload fresh data from localStorage every visit
        if (page === 'rapport' && window.rapportApp && typeof window.rapportApp.refreshAndRender === 'function') {
            window.rapportApp.refreshAndRender();
        }
    }
}

class BudgetApp {
    constructor() {
        this.expenses = this.loadExpenses();
        this.form = document.getElementById('expenseForm');
        this.amountInput = document.getElementById('amount');
        this.categoryInput = document.getElementById('category');
        this.dateInput = document.getElementById('date');
        this.expensesList = document.getElementById('expensesList');
        this.categorySummary = document.getElementById('categorySummary');

        this.setupEventListeners();
        this.setTodayDate();
        this.render();
        currencyManager.onCurrencyChange((currency) => this.onCurrencyChange(currency));

        // Initialize Router after BudgetApp is ready
        this.router = new Router();
    }

    setupEventListeners() {
        this.form.addEventListener('submit', (e) => this.handleAddExpense(e));
    }

    setTodayDate() {
        const today = new Date().toISOString().split('T')[0];
        this.dateInput.value = today;
    }

    handleAddExpense(e) {
        e.preventDefault();

        const expense = {
            id: Date.now(),
            amount: parseFloat(this.amountInput.value),
            category: this.categoryInput.value,
            date: this.dateInput.value
        };

        this.expenses.push(expense);
        this.saveExpenses();
        this.form.reset();
        this.setTodayDate();
        this.render();
    }

    saveExpenses() {
        localStorage.setItem('expenses', JSON.stringify(this.expenses));
    }

    loadExpenses() {
        const stored = localStorage.getItem('expenses');
        return stored ? JSON.parse(stored) : [];
    }

    getCategorySummary() {
        const summary = {};
        this.expenses.forEach(expense => {
            if (!summary[expense.category]) {
                summary[expense.category] = 0;
            }
            summary[expense.category] += expense.amount;
        });
        return summary;
    }

    renderCategorySummary() {
        const summary = this.getCategorySummary();

        if (Object.keys(summary).length === 0) {
            this.categorySummary.innerHTML = `<p class="empty-message">${translationManager.get('no_expense')}</p>`;
            this.updateBalance();
            return;
        }

        this.categorySummary.innerHTML = Object.entries(summary)
            .sort((a, b) => b[1] - a[1])
            .map(([category, total]) => `
                <div class="category-item">
                    <div class="category-name">${category}</div>
                    <div class="category-total">${currencyManager.format(total)}</div>
                </div>
            `)
            .join('');

        this.updateBalance();
    }

    renderExpensesList() {
        if (this.expenses.length === 0) {
            this.expensesList.innerHTML = `<p class="empty-message">${translationManager.get('no_expense')}</p>`;
            return;
        }

        const sorted = [...this.expenses].sort((a, b) => new Date(b.date) - new Date(a.date));

        this.expensesList.innerHTML = sorted
            .map(expense => `
                <div class="expense-item">
                    <div class="expense-info">
                        <div class="expense-date">${this.formatDate(expense.date)}</div>
                        <div class="expense-category">${expense.category}</div>
                    </div>
                    <div class="expense-amount">${currencyManager.format(expense.amount)}</div>
                </div>
            `)
            .join('');
    }

    formatDate(dateString) {
        const options = { year: 'numeric', month: 'long', day: 'numeric' };
        return new Date(dateString).toLocaleDateString('fr-FR', dateString);
    }

    render() {
        this.renderCategorySummary();
        this.renderExpensesList();
        if (typeof translateEntireDOM === 'function') translateEntireDOM();
    }

    getBalance() {
        const expenseTotal = this.expenses.reduce((sum, expense) => sum + expense.amount, 0);
        const incomeTotal = window.incomeApp ? window.incomeApp.getIncomeTotal() : 0;

        // Calculate total subscriptions
        let subscriptionsTotal = 0;
        if (window.subscriptionsApp) {
            subscriptionsTotal = window.subscriptionsApp.calculateMonthlyTotal();
        }

        // Calculate total goals (amount already saved)
        let goalsTotal = 0;
        if (window.goalsApp) {
            goalsApp.goals.forEach(goal => {
                goalsTotal += goal.currentAmount;
            });
        }

        return incomeTotal - expenseTotal - subscriptionsTotal - goalsTotal;
    }

    updateBalance() {
        const balanceElement = document.getElementById('balanceAmount');
        if (balanceElement) {
            const balance = this.getBalance();
            balanceElement.textContent = currencyManager.format(balance);
        }
    }

    onCurrencyChange(newCurrency) {
        this.render();
        this.updateBalance();
    }
}

function updateCurrencyLabels() {
    const currentSymbol = currencyManager.getSymbol();
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        null,
        false
    );

    let node;
    while (node = walker.nextNode()) {
        const text = node.textContent;
        if (text.includes('(€)') || text.includes('($)')) {
            node.textContent = text.replace(/\([€$]\)/g, `(${currentSymbol})`);
        }
    }
}

